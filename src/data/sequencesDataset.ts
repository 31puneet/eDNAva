export const INITIAL_DATASET_SEQUENCES: SequenceRecord[] = Array.from({ length: 200 }, (_, index) => {
  const paddedIndex = String(index).padStart(4, '0');
  const id = `SEQ_${paddedIndex}`;
  const baseSeq = rawBaseSequences[index % rawBaseSequences.length];
  // Slightly adjust slice length to reflect realistic read length variations (198bp - 208bp)
  const sliceLen = 198 + ((index * 3) % 11);
  const seq = baseSeq.slice(0, sliceLen);
  const len = seq.length;
  const gc = calculateGC(seq);

  return {
    id,
    seq,
    len,
    gc,
    status: 'Pending classification',
  };
});

/** Single Record CSV Export */
export function exportSingleReadToCSV(record: SequenceRecord) {
  const headers = ['read_id', 'dna_sequence', 'sequence_length_bp', 'gc_content_pct', 'classification_status'];
  const row = [
    record.id,
    `"${record.seq}"`,
    record.len,
    `${record.gc}%`,
    `"${record.status}"`,
  ];
  const csvContent = `${headers.join(',')}\n${row.join(',')}`;
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `${record.id}_eDNA_read.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/** Single Record JSON Export */
export function exportSingleReadToJSON(record: SequenceRecord) {
  const jsonContent = JSON.stringify(record, null, 2);
  const blob = new Blob([jsonContent], { type: 'application/json;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `${record.id}_eDNA_read.json`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}

/** Bulk CSV Export for Filtered Dataset */
export function exportBulkToCSV(records: SequenceRecord[]) {
  const headers = ['read_id', 'dna_sequence', 'sequence_length_bp', 'gc_content_pct', 'classification_status'];
  const rows = records.map((r) => [
    r.id,
    `"${r.seq}"`,
    r.len,
    `${r.gc}%`,
    `"${r.status}"`,
  ].join(','));

  const csvContent = `${headers.join(',')}\n${rows.join('\n')}`;
  const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
  const url = URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.setAttribute('href', url);
  link.setAttribute('download', `eDNA_bulk_dataset_${records.length}_reads.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  URL.revokeObjectURL(url);
}
