export function calculateGC(seq: string): number {
  if (!seq || seq.length === 0) return 0;
  const matches = seq.match(/[GCgc]/g);
  const count = matches ? matches.length : 0;
  return parseFloat(((count / seq.length) * 100).toFixed(1));
}

